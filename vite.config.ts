import { fileURLToPath, URL } from 'node:url';
import { readFileSync } from 'node:fs';
import { defineConfig, type Plugin } from 'vitest/config';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { VitePWA } from 'vite-plugin-pwa';
import {
  SPLASH_DEVICES,
  SPLASH_THEMES,
  splashFileName,
  splashMedia,
} from './scripts/splashScreens.ts';

const BASE = '/Cockpit/';

const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')) as {
  version: string;
};

/** Background of the dark theme (= --bg in src/styles/tokens.css). */
const THEME_COLOR = '#090D16';

/**
 * Content-Security-Policy as meta tag. Only added to production builds, because the
 * Vite dev server relies on inline scripts/styles for HMR. Extend deliberately, each with the
 * step that needs it: Google (OAuth, Calendar, Gmail) in step 4, api.anthropic.com for the
 * optional AI in step 3.
 */
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join('; ');

function cspPlugin(): Plugin {
  return {
    name: 'cockpit-csp',
    apply: 'build',
    transformIndexHtml: {
      order: 'post',
      handler: () => [
        {
          tag: 'meta',
          attrs: { 'http-equiv': 'Content-Security-Policy', content: CSP },
          injectTo: 'head-prepend',
        },
      ],
    },
  };
}

/** iOS startup images (generated by npm run icons) as apple-touch-startup-image links. */
function splashPlugin(): Plugin {
  return {
    name: 'cockpit-splash',
    transformIndexHtml: () =>
      SPLASH_DEVICES.flatMap((device) =>
        (['portrait', 'landscape'] as const).flatMap((orientation) =>
          SPLASH_THEMES.map((theme) => ({
            tag: 'link',
            attrs: {
              rel: 'apple-touch-startup-image',
              media: splashMedia(device, orientation, theme),
              href: `${BASE}splash/${splashFileName(device, orientation, theme)}`,
            },
            injectTo: 'head' as const,
          })),
        ),
      ),
  };
}

